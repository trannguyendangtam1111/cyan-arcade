-- Daily challenges earn coins as well as XP. Challenges of earlier days stay as they were; the ones
-- already made for today and tomorrow get the coins their templates now give.
ALTER TABLE daily_challenges
    ADD COLUMN coin_reward INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_daily_challenges_coin_reward CHECK (coin_reward >= 0);
UPDATE daily_challenges SET coin_reward = xp_reward * 2
WHERE challenge_date >= (now() AT TIME ZONE 'UTC')::date;

-- A challenge is now about a game (as before) or about something else players do on the platform,
-- an "activity" such as opening card packs, counted over the day (goal COUNT).
ALTER TABLE daily_challenges
    ALTER COLUMN game_id DROP NOT NULL,
    ADD COLUMN activity VARCHAR(40),
    ADD COLUMN activity_name VARCHAR(40),
    ADD CONSTRAINT ck_daily_challenges_subject CHECK ((game_id IS NULL) <> (activity IS NULL)),
    ADD CONSTRAINT ck_daily_challenges_activity_name CHECK ((activity IS NULL) = (activity_name IS NULL)),
    DROP CONSTRAINT ck_daily_challenges_goal,
    ADD CONSTRAINT ck_daily_challenges_goal CHECK (goal IN ('PLAY', 'SCORE', 'DETAIL', 'COUNT')),
    ADD CONSTRAINT ck_daily_challenges_count CHECK ((goal = 'COUNT') = (activity IS NOT NULL));
-- One challenge per activity and day, as there is one per game and day.
CREATE UNIQUE INDEX uq_daily_challenges_date_activity ON daily_challenges (challenge_date, activity)
    WHERE activity IS NOT NULL;

-- How far each player has got with a counted challenge.
CREATE TABLE daily_challenge_progress (
    user_id            BIGINT      NOT NULL,
    daily_challenge_id BIGINT      NOT NULL,
    progress           INTEGER     NOT NULL,
    updated_at         TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_daily_challenge_progress PRIMARY KEY (user_id, daily_challenge_id),
    CONSTRAINT fk_daily_challenge_progress_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_daily_challenge_progress_challenge FOREIGN KEY (daily_challenge_id)
        REFERENCES daily_challenges (id),
    CONSTRAINT ck_daily_challenge_progress CHECK (progress >= 0)
);

