-- The platform economy: coins, the daily login reward, the shop, and counted daily challenges.

-- Each player's coin balance, kept next to the ledger for cheap reads. Changed only together with a
-- new row in coin_transactions, inside one transaction, while this row is locked. A player without
-- a row has 0 coins.
CREATE TABLE user_wallets (
    user_id    BIGINT      PRIMARY KEY,
    balance    BIGINT      NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_user_wallets_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- The last line of defence against spending coins one does not have.
    CONSTRAINT ck_user_wallets_balance CHECK (balance >= 0)
);

-- Every change to a balance, never updated or deleted: the balance is always the sum of these.
CREATE TABLE coin_transactions (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    -- Positive when coins are earned, negative when they are spent.
    amount         INTEGER      NOT NULL,
    balance_after  BIGINT       NOT NULL,
    type           VARCHAR(30)  NOT NULL,
    -- What the change is about, e.g. GAME_SESSION + its id, or ACHIEVEMENT + its code.
    reference_type VARCHAR(30),
    reference_id   VARCHAR(64),
    description    VARCHAR(200) NOT NULL,
    -- Who made the change when it was not the player's own doing: the admin behind an ADMIN_GRANT.
    created_by     BIGINT,
    created_at     TIMESTAMPTZ  NOT NULL,

    CONSTRAINT fk_coin_transactions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_coin_transactions_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_coin_transactions_amount CHECK (amount <> 0),
    CONSTRAINT ck_coin_transactions_balance_after CHECK (balance_after >= 0),
    CONSTRAINT ck_coin_transactions_type CHECK (type IN ('GAME_COMPLETION', 'HIGH_SCORE', 'ACHIEVEMENT',
        'DAILY_CHALLENGE', 'DAILY_LOGIN', 'SHOP_PURCHASE', 'ADMIN_GRANT')),
    CONSTRAINT ck_coin_transactions_reference CHECK ((reference_type IS NULL) = (reference_id IS NULL))
);

-- What makes a reward impossible to pay twice: one row per player, kind and thing rewarded.
CREATE UNIQUE INDEX uq_coin_transactions_reference
    ON coin_transactions (user_id, type, reference_id) WHERE reference_id IS NOT NULL;
-- "My transactions", newest first; also coins earned and today's game rewards of one player.
CREATE INDEX ix_coin_transactions_user_created ON coin_transactions (user_id, created_at DESC, id DESC);
-- Recent activity across all players, for the admin dashboard.
CREATE INDEX ix_coin_transactions_created ON coin_transactions (created_at);

-- One row per player and day on which they claimed the daily login reward. The primary key is what
-- stops a day being claimed twice.
CREATE TABLE daily_logins (
    user_id    BIGINT      NOT NULL,
    -- The server's date (UTC) of the claim; never one sent by the client.
    login_date DATE        NOT NULL,
    -- Consecutive days claimed, this one included.
    streak     INTEGER     NOT NULL,
    coins      INTEGER     NOT NULL,
    claimed_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_daily_logins PRIMARY KEY (user_id, login_date),
    CONSTRAINT fk_daily_logins_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_daily_logins_streak CHECK (streak > 0),
    CONSTRAINT ck_daily_logins_coins CHECK (coins >= 0)
);

-- What the shop sells. What an item does once bought is decided by its type, in the application.
CREATE TABLE shop_items (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL,
    name        VARCHAR(60)  NOT NULL,
    description VARCHAR(200) NOT NULL,
    -- PACK (extra card packs), BADGE and TITLE (shown on the profile), COSMETIC (owned, for later use).
    type        VARCHAR(20)  NOT NULL,
    price       INTEGER      NOT NULL,
    -- Units one purchase gives, e.g. 3 packs.
    quantity    INTEGER      NOT NULL DEFAULT 1,
    -- How many a player may own at most; NULL for no limit.
    max_owned   INTEGER,
    -- The level a player must have reached to buy it.
    min_level   INTEGER      NOT NULL DEFAULT 1,
    -- A name the frontend turns into a picture.
    icon        VARCHAR(30)  NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order  INTEGER      NOT NULL DEFAULT 0,

    CONSTRAINT uq_shop_items_code UNIQUE (code),
    CONSTRAINT ck_shop_items_type CHECK (type IN ('PACK', 'BADGE', 'TITLE', 'COSMETIC')),
    CONSTRAINT ck_shop_items_price CHECK (price > 0),
    CONSTRAINT ck_shop_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_shop_items_max_owned CHECK (max_owned IS NULL OR max_owned > 0),
    CONSTRAINT ck_shop_items_min_level CHECK (min_level >= 1)
);

-- What each player owns.
CREATE TABLE user_inventory (
    user_id     BIGINT      NOT NULL,
    item_id     BIGINT      NOT NULL,
    quantity    INTEGER     NOT NULL,
    -- For badges and titles: the one of each type the player shows on their profile.
    equipped    BOOLEAN     NOT NULL DEFAULT FALSE,
    acquired_at TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_user_inventory PRIMARY KEY (user_id, item_id),
    CONSTRAINT fk_user_inventory_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_inventory_item FOREIGN KEY (item_id) REFERENCES shop_items (id),
    CONSTRAINT ck_user_inventory_quantity CHECK (quantity >= 0)
);

-- Every purchase. The client gives each purchase attempt a random id; repeating a request with the
-- same id finds the purchase already made instead of buying again.
CREATE TABLE purchases (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    item_id    BIGINT      NOT NULL,
    price      INTEGER     NOT NULL,
    quantity   INTEGER     NOT NULL,
    request_id UUID        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_purchases_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_purchases_item FOREIGN KEY (item_id) REFERENCES shop_items (id),
    CONSTRAINT uq_purchases_request UNIQUE (user_id, request_id),
    CONSTRAINT ck_purchases_price CHECK (price > 0),
    CONSTRAINT ck_purchases_quantity CHECK (quantity > 0)
);

CREATE INDEX ix_purchases_user_created ON purchases (user_id, created_at DESC);

