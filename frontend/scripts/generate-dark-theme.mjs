// Generates src/styles/theme-dark.css from Tailwind's own palette values:
//   node scripts/generate-dark-theme.mjs
import fs from 'node:fs'

const themeCss = 'node_modules/tailwindcss/theme.css'
const out = 'src/styles/theme-dark.css'
const source = fs.readFileSync(themeCss, 'utf8')
const value = {}
for (const match of source.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) value[`${match[1]}-${match[2]}`] = match[3].trim()
const families = ['slate', 'gray', 'zinc', 'neutral', 'stone', 'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose']
// Light tints become dark and dark inks light; the bright middle and the darkest ink (950, used on
// bright fills) stay as they are.
const swap = { 50: 950, 100: 900, 200: 800, 700: 300, 800: 200, 900: 100 }
const dark = []
const keep = []
for (const family of families) {
  for (const [shade, from] of Object.entries(swap)) {
    const original = value[`${family}-${shade}`]
    const mirrored = value[`${family}-${from}`]
    if (!original || !mirrored) throw new Error(`No ${family}-${shade}`)
    dark.push(`    --color-${family}-${shade}: ${mirrored};`)
    keep.push(`    --color-${family}-${shade}: ${original};`)
  }
}
const css = `/*
 * The dark theme (html[data-theme='dark'], set by public/theme-init.js and lib/theme.ts).
 *
 * The semantic tokens (canvas, surface, ink, line, shadows) get dark values in index.css. This file
 * mirrors Tailwind's colour scales so that the palette classes used across the app follow too:
 * light tints (50, 100, 200) become the matching dark shades and dark inks (700, 800, 900) the
 * matching light ones, so "a pale amber badge with dark amber text" becomes "a dark amber badge
 * with pale amber text". The bright middle (300 to 600) and the darkest ink (950, used on bright
 * fills) stay as they are.
 *
 * Game playfields ([data-theme-keep]: the boards of the arcade games) keep the original palette,
 * so a 2048 tile or a Minesweeper cell looks the same in both themes.
 *
 * Generated by scripts/generate-dark-theme.mjs from Tailwind's palette: regenerate rather than edit.
 */
@layer base {
  html[data-theme='dark'] {
${dark.join('\n')}
  }

  html[data-theme='dark'] [data-theme-keep] {
${keep.join('\n')}
  }
}
`
fs.writeFileSync(out, css)
console.log(`${families.length} families, ${dark.length} variables`)
